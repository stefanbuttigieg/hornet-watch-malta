CREATE TABLE public.reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  type text NOT NULL CHECK (type IN ('sighting','nest','hive_damage','intervention')),
  lat double precision NOT NULL CHECK (lat BETWEEN 35.78 AND 36.10),
  lng double precision NOT NULL CHECK (lng BETWEEN 14.15 AND 14.60),
  locality text,
  observed_on date NOT NULL DEFAULT current_date,
  hornet_count integer CHECK (hornet_count IS NULL OR hornet_count BETWEEN 0 AND 10000),
  behaviour text,
  nest_status text,
  hives_total integer CHECK (hives_total IS NULL OR hives_total BETWEEN 0 AND 5000),
  hives_lost integer CHECK (hives_lost IS NULL OR hives_lost BETWEEN 0 AND 5000),
  intervention_type text,
  notes text CHECK (notes IS NULL OR length(notes) <= 1000),
  photo_url text,
  is_demo boolean NOT NULL DEFAULT false,
  hidden boolean NOT NULL DEFAULT false,
  flag_count integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.trap_catches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  report_id uuid NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  caught_on date NOT NULL DEFAULT current_date,
  count integer NOT NULL CHECK (count BETWEEN 0 AND 10000),
  created_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT ON public.reports TO anon, authenticated;
GRANT SELECT, INSERT ON public.trap_catches TO anon, authenticated;
GRANT ALL ON public.reports, public.trap_catches TO service_role;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trap_catches ENABLE ROW LEVEL SECURITY;
CREATE POLICY "public read visible" ON public.reports FOR SELECT TO anon, authenticated USING (hidden = false);
CREATE POLICY "public insert" ON public.reports FOR INSERT TO anon, authenticated WITH CHECK (hidden = false AND flag_count = 0 AND is_demo = false);
CREATE POLICY "public read catches" ON public.trap_catches FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public insert catches" ON public.trap_catches FOR INSERT TO anon, authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM public.reports r WHERE r.id = report_id AND r.type='intervention' AND r.hidden=false));
CREATE OR REPLACE FUNCTION public.flag_report(_id uuid) RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path=public AS
$$ UPDATE public.reports SET flag_count = flag_count + 1 WHERE id = _id AND hidden = false; $$;
REVOKE EXECUTE ON FUNCTION public.flag_report(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.flag_report(uuid) TO anon, authenticated;
CREATE POLICY "public upload report photos" ON storage.objects FOR INSERT TO anon, authenticated WITH CHECK (bucket_id = 'report-photos');
CREATE POLICY "public read report photos" ON storage.objects FOR SELECT TO anon, authenticated USING (bucket_id = 'report-photos');

